import re

def clean_text(text):
    """
    去除文本中的换行符、从**符号到：符号的内容，以及数字序号（如1. 2. 3.）
    
    参数:
        text (str): 需要处理的文本
        
    返回:
        str: 处理后的文本
    """
    # 去除换行符
    text = text.replace('\n', ' ')
    
    # 使用正则表达式去除**到：之间的内容
    pattern = r'\*\*.*?：'
    text = re.sub(pattern, '', text)
    
    # 去除数字序号（如1. 2. 3.）
    text = re.sub(r'\d+\.', '', text)
    
    # 去除多余的空格
    text = ' '.join(text.split())
    
    return text

